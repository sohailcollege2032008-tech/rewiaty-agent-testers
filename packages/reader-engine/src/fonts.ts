export function normalizeFontBaseUrl(baseUrl: string): string {
  const sanitized = baseUrl.trim().replace(/['"\\<>()\r\n]/g, '');
  if (!sanitized) return '';
  return sanitized.endsWith('/') ? sanitized : `${sanitized}/`;
}

export function buildFontFaceCss(fontBaseUrl: string): string {
  const base = normalizeFontBaseUrl(fontBaseUrl);
  if (!base) return '';
  return READER_FONT_FACES.map(
    (f) =>
      `@font-face{font-family:'${f.family}';font-style:${f.style};font-weight:${f.weight};font-display:swap;src:url('${base}${f.fileName}') format('woff2');unicode-range:${f.unicodeRange};}`,
  ).join('\n');
}
